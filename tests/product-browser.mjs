import { createRequire } from 'node:module'
import assert from 'node:assert/strict'
const require = createRequire(process.env.CODEX_NODE_PACKAGES + '/package.json')
const { chromium } = require('playwright')
const browser = await chromium.launch({ headless: true, channel: 'msedge' })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
const errors = []
page.on('pageerror', (error) => errors.push(error.message))
await page.goto('http://127.0.0.1:5173/san-pham/iphone-pro')
await page.getByRole('heading', { name: 'iPhone 17 Pro', exact: true }).waitFor()
await page.screenshot({ path: 'docs/previews/product-desktop.png', fullPage: true })
assert.equal(await page.locator('.pdp-layout > aside').count(), 1)
assert.equal(await page.locator('vite-error-overlay').count(), 0)
await page.getByRole('button', { name: '512GB · Cam', exact: false }).isDisabled().then((value) => assert(value))
await page.getByRole('button', { name: 'Thêm vào giỏ hàng', exact: true }).click()
await page.getByRole('dialog').waitFor()
assert.match(await page.getByRole('dialog').innerText(), /iPhone 17 Pro/)
await page.keyboard.press('Escape')
await page.getByRole('button', { name: 'Đặt mua', exact: true }).click()
assert.match(await page.getByRole('dialog').innerText(), /256GB · Cam/)
await page.keyboard.press('Escape')
await page.getByRole('button', { name: 'Viết nhận xét', exact: true }).click()
await page.getByRole('button', { name: 'Đăng nhận xét dùng thử' }).click()
await page.getByText('Vui lòng nhập tên.', { exact: true }).waitFor()
await page.getByLabel('Tên của bạn').fill('Người dùng thử')
await page.getByLabel('Nhận xét của bạn').fill('Giao diện chọn phiên bản rõ ràng.')
await page.getByRole('dialog').locator('.ant-rate-star').nth(4).click()
await page.getByRole('button', { name: 'Đăng nhận xét dùng thử' }).click()
await page.getByText('Giao diện chọn phiên bản rõ ràng.', { exact: true }).waitFor()
assert.match(await page.locator('.pdp-rating-summary').innerText(), /5.0/)
await page.getByRole('tab', { name: 'Thông số kỹ thuật', exact: true }).click()
await page.getByText('Phiên bản đang chọn', { exact: true }).waitFor()
await page.getByRole('tab', { name: 'Mô tả', exact: true }).click()
await page.getByRole('button', { name: 'Xem thêm mô tả', exact: true }).click()
await page.getByText('Những điểm đáng chú ý', { exact: true }).waitFor()
await page.getByRole('button', { name: 'Bảo hành Thông tin và điều kiện bảo hành' }).click()
await page.getByRole('dialog').waitFor()
await page.keyboard.press('Escape')
for (const width of [360, 640, 641, 735, 736, 833, 834, 1068, 1069, 1440]) {
  await page.setViewportSize({ width, height: 1000 })
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), `Overflow at ${width}`)
  if ([360, 834].includes(width)) await page.screenshot({ path: `docs/previews/product-${width}.png`, fullPage: true })
}
await page.goto('http://127.0.0.1:5173/san-pham/air-13')
await page.getByRole('button', { name: '16GB / 512GB · Xanh', exact: false }).click()
assert.match(await page.locator('.pdp-total').innerText(), /29.990.000/)
await page.goto('http://127.0.0.1:5173/san-pham/msi-mainboard')
await page.getByRole('heading', { name: 'MSI B650 Gaming Plus WiFi', exact: true }).waitFor()
assert(await page.getByRole('button', { name: 'Đặt mua', exact: true }).isDisabled())
await page.goto('http://127.0.0.1:5173/san-pham/missing-product')
await page.getByRole('heading', { name: 'Chưa thể mở sản phẩm' }).waitFor()
await page.goto('http://127.0.0.1:5173/')
await page.getByRole('link', { name: 'Xem iPhone 17 Pro', exact: true }).click()
await page.getByRole('heading', { name: 'iPhone 17 Pro', exact: true }).waitFor()
assert.equal(await page.locator('img').evaluateAll((images) => images.filter((image) => image.complete && !image.naturalWidth).length), 0)
assert.deepEqual(errors, [])
console.log('PASS: detail route, navigation, variants/price, sold out, cart, order preview, review validation/submission, policies, tabs, expand, 10 viewport widths, no page errors or broken loaded images.')
await browser.close()
