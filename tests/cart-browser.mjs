import { createRequire } from 'node:module'
import assert from 'node:assert/strict'
const require = createRequire(process.env.CODEX_NODE_PACKAGES + '/package.json')
const { chromium } = require('playwright')
const browser = await chromium.launch({ channel: 'msedge', headless: true })
try {
  const page = await browser.newPage()
  const errors = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('http://127.0.0.1:5173/cart')
  await page.getByText('Giỏ hàng của bạn đang trống.', { exact: true }).waitFor()
  await page.evaluate(() => localStorage.setItem('chanh-man:cart:v1', JSON.stringify([
    { variantId: 'air-13-256', quantity: 2 }, { variantId: 'air-13-512', quantity: 1 },
  ])))
  await page.reload()
  await page.getByRole('button', { name: 'Giỏ hàng, 3 sản phẩm' }).waitFor()
  assert.equal(await page.locator('.cart-page .cart-item').count(), 2)
  const quantity = page.getByRole('spinbutton').first()
  await quantity.fill('3')
  await quantity.press('Tab')
  await page.getByRole('button', { name: 'Giỏ hàng, 4 sản phẩm' }).waitFor()
  assert.match(await page.locator('.cart-page-summary').innerText(), /104.960.000/)
  await page.reload()
  await page.getByRole('button', { name: 'Giỏ hàng, 4 sản phẩm' }).waitFor()
  assert.equal(await page.getByRole('link', { name: 'Tiếp tục đặt hàng' }).getAttribute('href'), '/checkout')
  for (const width of [360, 640, 641, 768, 833, 834, 1068, 1440]) {
    await page.setViewportSize({ width, height: 900 })
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `overflow ${width}`)
    const removeSize = await page.locator('.cart-page .cart-item-controls button').first().boundingBox()
    assert(removeSize.width >= 44 && removeSize.height >= 44, `remove touch target ${width}`)
    if ([360, 768, 1440].includes(width)) await page.screenshot({ path: `docs/previews/cart-${width}.png`, fullPage: true })
  }
  await page.getByRole('button', { name: 'Giỏ hàng, 4 sản phẩm' }).click()
  const dialog = page.getByRole('dialog')
  await dialog.waitFor()
  const drawerRemoveSize = await dialog.locator('.cart-item-controls button').first().boundingBox()
  assert(drawerRemoveSize.width >= 44 && drawerRemoveSize.height >= 44, 'drawer remove touch target')
  await dialog.getByRole('button', { name: 'Xóa MacBook Air 13 inch 16GB / 512GB · Xanh', exact: true }).click()
  await page.getByRole('button', { name: 'Giỏ hàng, 3 sản phẩm' }).waitFor()
  await page.keyboard.press('Escape')
  assert.equal(await page.locator('.cart-page .cart-item').count(), 1)
  await page.getByRole('button', { name: 'Xóa MacBook Air 13 inch 16GB / 256GB · Xanh', exact: true }).click()
  await page.getByText('Giỏ hàng của bạn đang trống.', { exact: true }).waitFor()
  await page.getByRole('link', { name: 'Khám phá sản phẩm' }).click()
  await page.waitForURL('**/san-pham')
  await page.getByRole('heading', { name: 'Tất cả sản phẩm.' }).waitFor()
  await page.goto('http://127.0.0.1:5173/san-pham/air-13')
  await page.getByRole('button', { name: 'Thêm vào giỏ hàng', exact: true }).click()
  await page.getByRole('link', { name: 'Xem giỏ hàng', exact: true }).click()
  await page.waitForURL('**/cart')
  await page.getByRole('button', { name: 'Giỏ hàng, 1 sản phẩm' }).waitFor()
  assert.equal(await page.locator('.cart-page .cart-item').count(), 1)
  await page.evaluate(() => { Storage.prototype.setItem = () => { throw new Error('blocked') } })
  const remove = page.getByRole('button', { name: 'Xóa MacBook Air 13 inch 16GB / 256GB · Xanh', exact: true })
  await remove.focus()
  await page.keyboard.press('Enter')
  await page.getByRole('alert').filter({ hasText: 'Không thể lưu giỏ hàng' }).waitFor()
  assert.equal(await page.locator('.cart-page .cart-item').count(), 1)
  await page.reload()
  await page.getByRole('button', { name: 'Giỏ hàng, 1 sản phẩm' }).waitFor()
  await page.evaluate(() => localStorage.setItem('chanh-man:cart:v1', JSON.stringify([
    { variantId: 'air-13-256', quantity: 99 }, { variantId: 'iphone-pro-512', quantity: 1 },
  ])))
  await page.reload()
  await page.getByText('Giỏ hàng đã được cập nhật', { exact: true }).waitFor()
  assert.equal(await page.getByRole('spinbutton').inputValue(), '8')
  assert.deepEqual(errors, [])
  console.log('Cart browser checks passed: empty, quantity, totals, reload, drawer sync, navigation, responsive.')
} finally { await browser.close() }
