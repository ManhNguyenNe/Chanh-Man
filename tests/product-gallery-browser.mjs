import { createRequire } from 'node:module'
import assert from 'node:assert/strict'
const require = createRequire(process.env.CODEX_NODE_PACKAGES + '/package.json')
const { chromium } = require('playwright')
const browser = await chromium.launch({ channel: 'msedge', headless: true })
const page = await browser.newPage()
await page.goto('http://127.0.0.1:5173/san-pham/iphone-pro')
await page.getByRole('button', { name: 'Ảnh 2', exact: true }).click()
assert.match(await page.locator('.pdp-main-image img').getAttribute('src'), /transparent/)
await page.getByRole('button', { name: 'Phóng to ảnh iPhone 17 Pro' }).click()
await page.getByRole('dialog').waitFor()
await page.keyboard.press('Escape')
await page.getByRole('button', { name: 'Ảnh 1', exact: true }).click()
await page.getByRole('button', { name: 'Ảnh 1', exact: true }).focus()
await page.keyboard.press('Tab')
assert.equal(await page.getByRole('button', { name: 'Ảnh 2', exact: true }).evaluate((el) => el === document.activeElement), true)
await page.keyboard.press('Enter')
assert.equal(await page.getByRole('button', { name: 'Ảnh 2', exact: true }).getAttribute('aria-pressed'), 'true')
for (const [width, name] of [[1440, 'desktop'], [834, '834'], [360, '360']]) {
  await page.setViewportSize({ width, height: 1000 })
  await page.reload()
  await page.getByRole('heading', { name: 'iPhone 17 Pro', exact: true }).waitFor()
  await page.locator('.pdp-related').scrollIntoViewIfNeeded()
  await page.locator('.pdp-related img').evaluateAll((images) => Promise.all(images.map((image) => image.decode())))
  await page.evaluate(() => window.scrollTo({ top: 0, behavior: 'instant' }))
  await page.screenshot({ path: `docs/previews/product-${name}.png`, fullPage: true })
  if (width === 360) await page.screenshot({ path: 'docs/previews/product-mobile-top.png' })
}
console.log('PASS: gallery, image preview, keyboard navigation; captured loaded images at desktop, tablet, mobile.')
await browser.close()
